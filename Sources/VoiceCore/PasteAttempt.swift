import AppKit

/// Paste delivery is asynchronous. Posting Command-V is not evidence that a box received it.
public struct PasteAttempt {
    public enum Decision: Equatable { case wait, post, confirmed, failed(String) }
    public static let modifierTimeout = 1.2
    public static let deliveryTimeout = 2.0
    private let startedAt: Double
    private var releasedAt: Double?
    public private(set) var postedAt: Double?

    public init(at now: Double) { startedAt = now }

    public mutating func next(at now: Double, modifiersDown: Bool, sameTarget: Bool,
                              clipboardOwned: Bool, landed: Bool) -> Decision {
        guard sameTarget else { return .failed("target changed") }
        if let postedAt {
            if landed { return .confirmed }
            if now - postedAt >= Self.deliveryTimeout { return .failed("delivery not confirmed") }
            return .wait
        }
        guard clipboardOwned else { return .failed("clipboard changed before posting") }
        if modifiersDown { releasedAt = nil }
        else if releasedAt == nil { releasedAt = now }
        // A brief stable release avoids posting between two adjacent modifier transitions.
        if let releasedAt, now - releasedAt >= 0.03 {
            postedAt = now
            return .post
        }
        if now - startedAt >= Self.modifierTimeout { return .failed("shortcut keys still held") }
        return .wait
    }
}

/// Exact replacement evidence when the value is readable, otherwise the expected cursor movement.
public struct PasteEvidence {
    public let before: String?
    public let range: NSRange?
    private let text: String

    public init(before: String?, range: NSRange?, text: String) {
        self.before = before; self.range = range; self.text = text
    }

    public func landed(value: String?, range now: NSRange?) -> Bool {
        let cursorMoved = range.map { old in
            guard old.location >= 0, old.location < Int.max - text.utf16.count else { return false }
            return now == NSRange(location: old.location + text.utf16.count, length: 0) && now != old
        } ?? false
        if let before, let value {
            if let range, range.location >= 0, range.length >= 0, range.location <= before.utf16.count,
               range.length <= before.utf16.count - range.location {
                let expected = (before as NSString).replacingCharacters(in: range, with: text)
                return value == expected && (value != before || cursorMoved)
            }
            return value != before && value.contains(text)
        }
        return cursorMoved
    }
}

/// The same clipboard lifetime rules are used by the application and by checks on a private pasteboard.
public struct PasteClipboardLoan {
    public enum Finish: Equatable { case restored, kept, changed }
    private let pasteboard: NSPasteboard
    private let saved: ClipboardSnapshot
    private let mine: Int

    public init?(_ text: String, pasteboard: NSPasteboard = .general) {
        self.pasteboard = pasteboard
        saved = ClipboardSnapshot.take(pasteboard)
        pasteboard.clearContents()
        let item = NSPasteboardItem()
        item.setString(text, forType: .string)
        item.setData(Data(), forType: NSPasteboard.PasteboardType("org.nspasteboard.TransientType"))
        item.setData(Data(), forType: NSPasteboard.PasteboardType("org.nspasteboard.AutoGeneratedType"))
        guard pasteboard.writeObjects([item]) else { saved.restore(to: pasteboard); return nil }
        mine = pasteboard.changeCount
    }

    public var ownsClipboard: Bool { pasteboard.changeCount == mine }

    public func finish(confirmed: Bool) -> Finish {
        guard ownsClipboard else { return .changed }
        guard confirmed else { return .kept }
        saved.restore(to: pasteboard)
        return .restored
    }
}
